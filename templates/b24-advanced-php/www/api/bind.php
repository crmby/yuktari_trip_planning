<?php
declare(strict_types=1);
/**
 * api/bind.php — пересобрать плейсменты приложения (пункт меню, вкладки).
 *
 * POST → {ok:true, bound:{КОД:true|false}, errors:{КОД:текст}, actual:{КОД:HANDLER}}
 *
 * Обычно звать не нужно: объявленные в env.php плейсменты приложение привязывает
 * само при установке и при смене адреса (см. api/placements.php). Эта кнопка —
 * для случая «пункт меню кто-то удалил руками» и для проверки после правки
 * списка.
 *
 * Раньше здесь была служебная СТРАНИЦА, которую предлагалось открыть в браузере.
 * Открыть её было нельзя: пропуск приложения живёт в cookie под партицией
 * портала и на прямой адрес не отправляется — человек упирался в «Открой
 * приложение из меню портала» и шёл к разработчику. Поэтому теперь это обычный
 * эндпоинт с пропуском в заголовке, как все остальные.
 */

require_once __DIR__ . '/http.php';
require_once __DIR__ . '/placements.php';

installFailureHandler(true);

$ctx = apiBoot(['methods' => ['POST'], 'role' => 'admin']);

// МЕСТА В ПОРТАЛЕ И ПОДПИСКА НА СОБЫТИЯ — ДВА НЕЗАВИСИМЫХ ДОГОВОРА.
//
// Прежде пустой список мест обрывал запрос ЗДЕСЬ, и вместе с местами не
// пересобиралась подписка на события (находка ревью 08.08.2026, BXREV-010).
// У приложения без единого пункта меню, но с событиями, это означало: отвалился
// обработчик `ONAPPUNINSTALL` — вернуть его из интерфейса нечем, только полной
// переустановкой. Теперь события пересобираются всегда, а места — если объявлены.
$spec = placementSpec();
$b24 = b24();
$res = $spec === []
    ? ['bound' => [], 'errors' => []]
    : bindPlacements($b24, true);   // force: человек нажал кнопку осознанно

// Подписку на события пересобираем ТУТ ЖЕ и тоже принудительно. Человек жмёт эту
// кнопку по одной причине — «в портале что-то отвалилось», и обработчик события
// снимается ровно так же, как пункт меню. Пока обычные открытия защищены
// отпечатком (то есть в портал не ходят), эта кнопка — единственный способ
// переставить подписку, не переустанавливая приложение.
require_once __DIR__ . '/events-bind.php';
$eventsRes = bindEvents($b24, true);

auditLog('placements.rebind', [
    'коды'   => array_keys($res['bound']),
    'ошибки' => array_keys($res['errors']),
    'события' => array_keys($eventsRes['bound'] ?? []),
], $ctx['uid']);

apiOk([
    'bound'  => $res['bound'],
    'errors' => $res['errors'],
    // Что портал считает привязанным СЕЙЧАС: расхождение с объявленным — это и
    // есть ответ на вопрос «почему вкладки нет, хотя приложение работает».
    'actual' => $spec === [] ? [] : placementsActual($b24),
    'events' => [
        'bound'  => array_keys($eventsRes['bound'] ?? []),
        'errors' => $eventsRes['errors'] ?? [],
    ],
    // Пустой список мест — законное состояние, а не ошибка. Говорим об этом
    // прямо, но уже ПОСЛЕ того, как события пересобраны.
    'note'   => $spec === []
        ? 'Мест в портале не объявлено (APP_PLACEMENTS в www/env.php) — пересобрана только подписка на события.'
        : '',
]);
