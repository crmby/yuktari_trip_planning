/**
 * ДОСТУПНЫ ЛИ ПРИЛОЖЕНИЮ МЕТОДЫ ПОРТАЛА.
 *
 * ЗАЧЕМ. Выданное право (scope) и работающий метод — РАЗНЫЕ вещи. Особенно на
 * коробке: там модуль может быть выключен, версия портала старее, часть методов
 * просто отсутствует. Замер на живой коробке 08.08.2026: при 71 выданном праве и
 * 1175 доступных методах вызвать `crm.item.list` было НЕЛЬЗЯ.
 *
 * Приложение, которое этого не проверяет, узнаёт правду в середине работы:
 * половина выгрузки сделана, дальше сплошные отказы, отчёт неполный — а выглядит
 * законченным. Хуже всего, что случается это у клиента, а не у нас.
 *
 * ЧТО ДЕЛАЕМ. Спрашиваем портал ОДНИМ пакетом (`method.get` по 50 команд за раз,
 * предел портала) и запоминаем ответ. Дальше приложение может спросить у себя:
 * можно ли звать метод, чего не хватает, что сказать человеку.
 *
 * ГРАНИЦЫ, которые здесь важнее самой проверки:
 *
 *  1. НЕПРОВЕРЕННОЕ — РАЗРЕШЕНО. Пока проверка не проходила (первая установка,
 *     портал молчал, метод недоступен самому `method.get`), приложение работает
 *     как раньше. Обратное означало бы предохранитель, который останавливает
 *     всех, включая тех, у кого всё в порядке.
 *  2. НЕВНЯТНЫЙ ОТВЕТ — НЕ ЗАПРЕТ. Старая коробка может ответить иначе; считать
 *     это отказом значит остановить рабочее приложение на ровном месте.
 *  3. ОТКАЗ ПОРТАЛА НЕ ЗАТИРАЕТ ЗНАНИЕ. Прежняя карта остаётся: она вернее
 *     пустоты.
 *
 * Метод `method.get` (официальная документация, раздел common/system): принимает
 * `name` и отвечает парой `isExisting` (есть ли метод на портале) и `isAvailable`
 * (доступен ли он этому приложению). Разделять их обязательно: «метода нет» и
 * «метод есть, но вам нельзя» чинятся по-разному — обновлением портала и выдачей
 * прав соответственно.
 */

