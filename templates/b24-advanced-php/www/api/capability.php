/** Как часто перепроверять. Права и состав модулей меняют редко, но меняют. */
if (!defined('CAP_TTL_SEC')) define('CAP_TTL_SEC', 86400);

/**
 * Разобрать ответ портала по одному методу.
 *
 * @return string ok | нет доступа | нет на портале | неизвестно
 */
function capParseAnswer($otvet): string {
    if (!is_array($otvet)) return 'не ответил';
    // Ключи приходят как есть от портала; отсутствие ОБОИХ — это не «нельзя»,
    // а «портал ответил не то, что мы ждали».
    $est = array_key_exists('isExisting', $otvet);
    $dostupen = array_key_exists('isAvailable', $otvet);
    if (!$est && !$dostupen) return 'неизвестно';
    if ($est && !$otvet['isExisting']) return 'нет на портале';
    if ($dostupen && !$otvet['isAvailable']) return 'нет доступа';
    if ($dostupen && $otvet['isAvailable']) return 'ok';
    return 'неизвестно';
}

/** Прочитать сохранённую карту доступности. Пусто — ещё не спрашивали. */
function capRead(): array {
    if (!defined('CAP_FILE')) return [];
    $d = storeRead(CAP_FILE);
    return is_array($d) ? $d : [];
}

/** Устарела ли карта. */
function capStale(array $cap): bool {
    $at = (int)($cap['at'] ?? 0);
    return $at <= 0 || (time() - $at) >= CAP_TTL_SEC;
}

/**
 * Что известно про метод: ok · нет доступа · нет на портале · неизвестно ·
 * не ответил · не спрашивали.
 *
 * Отдельная функция появилась потому, что «мы не знаем» и «можно» — РАЗНЫЕ
 * вещи, а прежний код сводил их в одно логическое «да». Ревью 08.08.2026
 * показало цену: приложение уверенно звало метод, которого на портале нет,
 * а человек видел зелёный экран «всё доступно».
 */
function capState(string $method): string {
    $karta = capRead()['методы'] ?? [];
    $s = $karta[strtolower($method)] ?? null;
    return is_string($s) && $s !== '' ? $s : 'не спрашивали';
}

/**
 * Можно ли звать метод.
 *
 * ТРИ ИСХОДА, а не два. `$strogo` — для методов, объявленных обязательными:
 * там неизвестность приравнивается к запрету, потому что работа, начатая
 * вслепую, падает на середине и оставляет половину сделанного. Для остальных
 * непроверенное по-прежнему разрешено — иначе приложение не смогло бы сделать
 * ни одного вызова до первой проверки (см. границы в шапке файла).
 */
function capAllowed(string $method, bool $strogo = false): bool {
    $sostoyanie = capState($method);
    if ($sostoyanie === 'ok') return true;
    if ($sostoyanie === 'нет доступа' || $sostoyanie === 'нет на портале') return false;
    // «неизвестно», «не ответил», «не спрашивали» — знания нет. Строгий режим
    // такое не прощает, мягкий пропускает и оставляет след в состоянии.
    return $strogo === false;
}

/**
 * Чего из перечисленного не хватает.
 *
 * @param string[] $methods
 * @return string[] имена методов, которые портал назвал недоступными
 */
function capMissing(array $methods): array {
    $karta = capRead()['методы'] ?? [];
    $net = [];
    foreach ($methods as $m) {
        $s = $karta[strtolower((string)$m)] ?? null;
        if ($s === 'нет доступа' || $s === 'нет на портале') $net[] = (string)$m;
    }
    return $net;
}

/** Что показать человеку на экране «Состояние». */
function capHuman(): string {
    $cap = capRead();
    if (($cap['at'] ?? 0) <= 0) {
        return 'доступность методов портала ещё не проверялась';
    }
    $karta = (array)($cap['методы'] ?? []);
    $plohie = [];
    $bezOtveta = [];
    foreach ($karta as $imya => $sostoyanie) {
        if ($sostoyanie === 'ok') continue;
        // «Не ответил» и «неизвестно» — не отказ, но и не разрешение. Прежде они
        // молча считались нормой, и экран состояния говорил «всё доступно» там,
        // где половина методов не проверена вовсе.
        if ($sostoyanie === 'не ответил' || $sostoyanie === 'неизвестно') { $bezOtveta[] = (string)$imya; continue; }
        $plohie[] = $imya . ' — ' . $sostoyanie;
    }
    $hvost = $bezOtveta === []
        ? ''
        : '; не удалось проверить (' . count($bezOtveta) . '): ' . implode(', ', array_slice($bezOtveta, 0, 6))
            . (count($bezOtveta) > 6 ? ' и ещё ' . (count($bezOtveta) - 6) : '');
    if ($plohie === []) {
        $ok = count($karta) - count($bezOtveta);
        return ($bezOtveta === []
            ? 'все нужные методы портала доступны (' . count($karta) . ')'
            : 'доступны ' . $ok . ' из ' . count($karta) . ' методов портала') . ltrim($hvost, ';');
    }
    return 'недоступны методы портала: ' . implode('; ', array_slice($plohie, 0, 8))
        . (count($plohie) > 8 ? ' и ещё ' . (count($plohie) - 8) : '') . $hvost;
}

/**
 * Спросить портал о перечисленных методах и запомнить ответ.
 *
 * Пакетами по 50 — предел портала на команду `batch`. Список нужных методов у
 * приложения легко переваливает за полсотни, и «одним куском» такой пакет тихо
 * оборвался бы: часть методов осталась бы непроверенной, а карта выглядела бы
 * полной.
 *
 * @param string[] $methods
 * @param bool     $force  спросить, не глядя на срок
 */
function capRefresh(B24 $b24, array $methods, bool $force = false): array {
    $cap = capRead();
    $methods = array_values(array_unique(array_filter(array_map(
        static fn($m): string => strtolower(trim((string)$m)), $methods))));
    if ($methods === []) return $cap;

    // СВЕЖЕСТЬ НЕ РАВНА ПОЛНОТЕ. Прежний код отдавал свежую карту целиком, не
    // глядя, есть ли в ней то, что спросили: добавили в приложение функцию с
    // новым методом — и он проходил как непроверенный, хотя проверка формально
    // была выполнена сутки назад (находка ревью 08.08.2026). Теперь свежесть
    // засчитывается только для методов, которые в карте ЕСТЬ, а недостающие
    // спрашиваются отдельно.
    $bylo = (array)($cap['методы'] ?? []);
    $netvKarte = array_values(array_filter($methods,
        static fn(string $m): bool => !array_key_exists($m, $bylo)));
    $ustarela = capStale($cap) || $cap === [];
    if (!$force && !$ustarela && $netvKarte === []) return $cap;
    $sprosit = ($force || $ustarela) ? $methods : $netvKarte;

    // Копим НАБЛЮДЕНИЯ этого прохода, а не готовую карту. Прежний код собирал
    // карту из прочитанного вначале снимка и сохранял её целиком: пока мы ходили
    // в портал, сосед успевал записать своё знание о ДРУГОМ методе — и оно
    // исчезало без следа (находка ревью R3-010, 09.08.2026, подтверждена двумя
    // процессами). Слияние идёт внутри замка, поверх актуального состояния.
    $nablyudeno = [];   // метод => ['sostoyanie' => …, 'at' => время ВОПРОСА порталу]
    $bezZnaniya = [];   // метод => true: ответа не получили, прежнее знание вернее
    $sprosheno = 0;
    $neotvetil = 0;
    foreach (array_chunk($sprosit, 50) as $kusok) {
        $cmd = [];
        foreach ($kusok as $i => $imya) $cmd[(string)$i] = ['method.get', ['name' => $imya]];
        // Отметка ставится ДО вопроса: ответ описывает портал в момент ВОПРОСА,
        // не позже. Иначе процесс, который завис на минуту с уже полученным
        // ответом, выглядел бы самым свежим и возвращал бы карту в прошлое.
        $sprosheno_v = microtime(true);
        $res = $b24->batch($cmd);
        $tela = $res['result']['result'] ?? null;
        if (!is_array($tela)) {
            // Портал не ответил или ответил не тем. Прежнее знание вернее пустоты.
            logAppError('доступность методов портала не проверена: '
                . (string)($res['error'] ?? 'ответ без result'));
            // Но то, что успели узнать в предыдущих пакетах, — знание, и терять
            // его из-за отказа на следующем пакете незачем. Метку полноты при
            // этом не двигаем: опрос оборвался, карта проверена НЕ вся.
            return capPersist($nablyudeno, $bezZnaniya, false, $sprosheno, $neotvetil, $cap);
        }
        // Ошибки ОТДЕЛЬНЫХ подкоманд лежат рядом с результатами. Прежний код их
        // не смотрел вовсе: подкоманда с ошибкой не давала тела, метод получал
        // «неизвестно», и уже известное «нет доступа» превращалось в разрешение.
        $oshibki = (array)($res['result']['result_error'] ?? []);
        foreach ($kusok as $i => $imya) {
            $klyuch = (string)$i;
            $sprosheno++;
            if (array_key_exists($klyuch, $oshibki)) {
                $kod = is_array($oshibki[$klyuch])
                    ? (string)($oshibki[$klyuch]['error'] ?? '')
                    : (string)$oshibki[$klyuch];
                // «Такого метода нет» — это ОТВЕТ, а не сбой связи.
                if (stripos($kod, 'METHOD_NOT_FOUND') !== false || stripos($kod, 'ERROR_METHOD_NOT_FOUND') !== false) {
                    $nablyudeno[$imya] = ['sostoyanie' => 'нет на портале', 'at' => $sprosheno_v];
                    continue;
                }
                // Любая другая ошибка — знания не прибавилось. Прежнее состояние
                // сохраняем: «нет доступа», выясненное вчера, вчера же и верно.
                $neotvetil++;
                $bezZnaniya[$imya] = true;
                continue;
            }
            $novoeSostoyanie = capParseAnswer($tela[$klyuch] ?? null);
            if ($novoeSostoyanie === 'не ответил') {
                $neotvetil++;
                $bezZnaniya[$imya] = true;
                continue;
            }
            $nablyudeno[$imya] = ['sostoyanie' => $novoeSostoyanie, 'at' => $sprosheno_v];
        }
    }

    // Метка времени означает «проверена ВСЯ карта», а не «мы куда-то ходили».
    // При частичном опросе (карта свежая, спросили только новые методы) двигать
    // её нельзя: иначе достаточно раз в сутки добавлять по одному методу, чтобы
    // остальные не перепроверялись НИКОГДА, и снятое в портале право оставалось
    // бы незамеченным (находка ревью 09.08.2026).
    $polnyyOpros = $force || $ustarela;
    $novoe = capPersist($nablyudeno, $bezZnaniya, $polnyyOpros, $sprosheno, $neotvetil, $cap);
    $karta = (array)($novoe['методы'] ?? []);
    $plohih = count(array_filter($karta, static fn($s): bool => $s !== 'ok' && $s !== 'неизвестно'));
    appLog($plohih ? 'error' : 'info', 'capability.check',
        ['проверено' => $sprosheno, 'недоступно' => $plohih],
        ['msg' => $plohih ? capHuman() : 'все нужные методы портала доступны']);
    return $novoe;
}

/**
 * Сохранить НАБЛЮДЕНИЯ поверх актуальной карты — под замком файла.
 *
 * Почему не «записать собранную карту». Между чтением карты и записью проходит
 * поход в портал: на 63 метода это два пакета и несколько секунд, а параллельный
 * запрос за это время успевает проверить свои методы и записать их. Запись
 * целиком стирала его знание (R3-010). Поэтому наружу отдаётся только то, что
 * мы САМИ увидели, а склейка идёт внутри `storeUpdate` — там, где состояние
 * заведомо актуально.
 *
 * ОТМЕТКА НАБЛЮДЕНИЯ решает второй случай: два процесса про ОДИН метод. Побеждает
 * не тот, кто записал последним, а тот, кто спрашивал портал позже; иначе
 * зависший процесс возвращал бы карту в прошлое и разрешал вызов, который портал
 * уже запретил.
 *
 * @param array $nablyudeno метод => ['sostoyanie' => …, 'at' => время вопроса]
 * @param array $bezZnaniya метод => true — ответа нет; прежнее знание вернее
 * @param array $cap        карта, прочитанная в начале прохода (для CLI без CAP_FILE)
 */
function capPersist(array $nablyudeno, array $bezZnaniya, bool $polnyyOpros,
        int $sprosheno, int $neotvetil, array $cap): array {
    // Узнать ничего не удалось и полноту подтверждать нечем — писать нечего.
    // Пустая запись поставила бы метку «карта проверена», и экран состояния
    // сказал бы «все методы доступны (0)» там, где портал просто не ответил.
    if ($nablyudeno === [] && $bezZnaniya === [] && !$polnyyOpros) return $cap;
    $slit = static function (array $prev) use ($nablyudeno, $bezZnaniya, $polnyyOpros,
            $sprosheno, $neotvetil): array {
        $karta = (array)($prev['методы'] ?? []);
        $kogda = (array)($prev['наблюдения'] ?? []);
        foreach ($nablyudeno as $imya => $chto) {
            // Более старый ответ не побеждает новый. Равенство отдаём себе: без
            // отметки у соседа (карта прежнего формата) наше знание точно свежее.
            if ((float)($kogda[$imya] ?? 0) > (float)$chto['at']) continue;
            $karta[$imya] = $chto['sostoyanie'];
            $kogda[$imya] = $chto['at'];
        }
        // «Не ответил» — не знание, а его отсутствие: ставим только там, где
        // никакого состояния ещё нет, и отметку наблюдения НЕ двигаем.
        foreach (array_keys($bezZnaniya) as $imya) {
            if (!array_key_exists($imya, $karta)) $karta[$imya] = 'не ответил';
        }
        return [
            'методы' => $karta,
            'наблюдения' => $kogda,
            'at' => $polnyyOpros ? time() : (int)($prev['at'] ?? 0),
            'спрошено' => $sprosheno,
            'без ответа' => $neotvetil,
        ];
    };
    if (defined('CAP_FILE')) return storeUpdate(CAP_FILE, $slit);
    // Стора нет (проект не объявил CAP_FILE) — считаем прочитанное вначале
    // актуальным: делить его всё равно не с кем.
    return $slit($cap);
}

/**
 * Список методов, которые приложению нужны. Задаётся проектом в env.php.
 *
 * Пустой список — законное состояние: приложение просто не объявило требований,
 * и проверять нечего. Придумывать требования за проект нельзя: «обязательный»
 * метод, которым он не пользуется, остановил бы работу без причины.
 *
 * @return array{обязательные: string[], необязательные: string[]}
 */
function capNeeded(): array {
    $ob = defined('APP_METHODS_REQUIRED') ? (array)APP_METHODS_REQUIRED : [];
    $ne = defined('APP_METHODS_OPTIONAL') ? (array)APP_METHODS_OPTIONAL : [];
    return ['обязательные' => array_values($ob), 'необязательные' => array_values($ne)];
}

/** Чего не хватает из ОБЯЗАТЕЛЬНОГО — по этому решают, можно ли начинать работу. */
function capMissingRequired(): array {
    return capMissing(capNeeded()['обязательные']);
}

/**
 * Какие права портал СЕЙЧАС признаёт за приложением.
 *
 * Сохранённая при установке строка scope — снимок момента: права в карточке
 * local-app меняют без переустановки, и портал начинает отдавать их сразу, а
 * наша строка остаётся прежней. После переустановки она и вовсе приходит как
 * «app». Экран состояния из-за этого показывал «не хватает прав» при полностью
 * выданных правах, и человек переустанавливал приложение по кругу (жалоба
 * 25.08.2026 — портал в тот момент отвечал на `scope`: crm, user, placement).
 *
 * Метод `scope` — читающий (api-reference/scopes/scope.md) и ничего не меняет.
 * Ответ держим в общей памяти пять минут: экран открывают подряд, а права так
 * часто не меняются.
 *
 * @return array<int,string> Пустой массив означает «портал не ответил», а НЕ
 *                           «прав нет»: считать отказ подтверждением нельзя.
 */
function capPortalScopes(B24 $b24): array {
    require_once __DIR__ . '/cache.php';
    return cacheRemember('portal-scope-v1', 300, static function () use ($b24): array {
        $otvet = $b24->callChecked('scope');
        $out = [];
        foreach ((array)$otvet as $odno) {
            $odno = strtolower(trim((string)$odno));
            if ($odno !== '' && !in_array($odno, $out, true)) $out[] = $odno;
        }
        return $out;
    });
}
