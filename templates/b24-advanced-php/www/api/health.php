<?php
declare(strict_types=1);
/**
 * api/health.php — состояние приложения одним ответом.
 *
 * GET → {ok:true, portal:{...}, owner:{...}, scopes:{...}, placements:{...}, cron:{...}, problems:[...]}
 *
 * Зачем. Раньше на вопрос «установилось ли, и почему не работает» человек не мог
 * ответить сам: интерфейс показывал «BX24: OK», а всё остальное — права, скоупы,
 * плейсменты, фоновая работа — жило в файлах на сервере. Любая проверка
 * превращалась в обращение к разработчику.
 *
 * Здесь собрано ровно то, что ломается на практике, и каждая проблема названа
 * вместе с действием: не «scope mismatch», а «в карточке приложения не хватает
 * права lists — добавьте и переустановите».
 */

require_once __DIR__ . '/http.php';
require_once __DIR__ . '/journal.php';
require_once __DIR__ . '/placements.php';
require_once __DIR__ . '/plan.php';       // тариф портала и предел темпа запросов
require_once __DIR__ . '/capability.php'; // доступность методов портала для этого приложения

installFailureHandler(true);

// Состояние показывает, кто владелец и какие права выданы, — это не для всех.
$ctx = apiBoot(['methods' => ['GET'], 'role' => 'admin', 'rate' => [30, 60],
    'rate_failure' => 'diagnostic']);
$stateBootstrap = $GLOBALS['__bxapp_state_bootstrap'] ?? null;
unset($GLOBALS['__bxapp_state_bootstrap']);

$problems = [];
$add = static function (string $what, string $action, string $tone = 'warn') use (&$problems): void {
    $problems[] = ['текст' => $what, 'что_сделать' => $action, 'важность' => $tone];
};
$readState = static function (string $file, string $label) use ($add): ?array {
    try {
        return storeRead($file) ?? [];
    } catch (StoreCorruptedException $e) {
        $add('Повреждено хранилище «' . $label . '» — его данные не считаются пустыми',
             'Не сохраняйте новые данные поверх файла. Передайте разработчику quarantine-копию и время этой проверки', 'error');
    } catch (Throwable $e) {
        $add('Хранилище «' . $label . '» сейчас недоступно — состояние неизвестно',
             'Проверьте права/место на диске и обновите экран; не считайте пустые поля подтверждением отсутствия данных', 'error');
    }
    return null;
};

if (($ctx['rate_failure'] ?? '') !== '') {
    $readState(RATELIMIT_FILE, 'счётчик частоты');
}

// ── Портал и токены ──────────────────────────────────────────────────────
$tokens = $readState(B24_TOKENS_FILE, 'установка и токены');
$installed = $tokens === null ? null : !empty($tokens['access_token']);
$portal = [
    'домен'     => (string)($tokens['domain'] ?? ''),
    'member_id' => (string)($tokens['member_id'] ?? ''),
    'установлено' => $installed,
];
if ($installed === false) {
    $add('Приложение не установлено: токенов портала нет',
         'Откройте приложение из карточки на портале под администратором', 'error');
}

// Событийный токен: без него портал может слать события, а приложение их не примет.
$hasAppToken = $tokens === null ? null : !empty($tokens['application_token']);
if ($installed === true && !$hasAppToken) {
    $add('Приложение не получило постоянный токен событий',
         'Переустановите приложение из карточки — токен приходит при установке. '
         . 'Пока его нет, события портала (обновление сделки и т.п.) приниматься не будут');
}

// ── Владелец и список доступа ────────────────────────────────────────────
$acl = aclLoad();
$ownerUid = (int)($acl['owner_uid'] ?? 0);
if ($installed === true && $ownerUid <= 0) {
    $add('Владелец приложения не зафиксирован',
         'Пусть администратор портала откроет приложение ещё раз — владельцем станет он', 'error');
}

// ── Скоупы: что объявлено против того, что выдано ────────────────────────
$savedScope = (string)($tokens['scope'] ?? '');
$granted = $tokens === null ? null
    : array_values(array_filter(array_map('trim', explode(',', strtolower($savedScope)))));
$needed  = defined('APP_SCOPES') ? APP_SCOPES : ['crm', 'user', 'placement'];
$missing = $granted === null ? null : array_values(array_diff($needed, $granted));
// СОХРАНЁННАЯ СТРОКА ПРАВ — СНИМОК МОМЕНТА УСТАНОВКИ, А НЕ ИСТИНА.
//
// Права в карточке local-app меняют без переустановки, и портал начинает их
// отдавать сразу, а наша строка остаётся прежней (после переустановки она и
// вовсе приходит как «app»). Человек видел «не хватает прав: crm, user,
// placement» при полностью выданных правах и переустанавливал приложение по
// кругу — жалоба 25.08.2026, портал в тот момент отвечал на `scope`
// «crm, user, placement».
//
// Поэтому спрашиваем портал — но ТОЛЬКО когда снимок говорит о нехватке:
// на здоровом приложении лишнего запроса нет. Ответ держим в общей памяти
// пять минут: экран открывают подряд, а права так часто не меняют.
if ($installed === true && $missing !== null && $missing !== []) {
    $portalScopes = null;
    try {
        $portalScopes = capPortalScopes(b24());
    } catch (Throwable $e) {
        // Портал не ответил — судим по снимку. Молчать нельзя: «прав не хватает»
        // и «спросить не удалось» человек лечит по-разному.
        $add('Не удалось спросить портал, какие права выданы приложению',
             'Строка ниже собрана по данным установки и может отстать от карточки приложения. '
             . 'Обновите экран через минуту');
    }
    if (is_array($portalScopes) && $portalScopes !== []) {
        $granted = $portalScopes;
        $missing = array_values(array_diff($needed, $granted));
    }
}
if ($installed === true && $missing !== null && $missing !== []) {
    $add('В карточке приложения не хватает прав: ' . implode(', ', $missing),
         'Добавьте эти права в карточке local-app на портале и нажмите «Переустановить»', 'error');
}

// ── Методы портала: право выдано ≠ метод работает ────────────────────────
// Отдельно от прав намеренно. На коробке модуль бывает выключен, а версия
// портала старее: замер на живой коробке — при 71 выданном праве `crm.item.list`
// вызвать нельзя. Пока это не названо, человек ищет причину в правах, которых
// ему как раз хватает, и переустанавливает приложение по кругу.
// Карта доступности читается на этом экране ДВАЖДЫ (здесь и ниже, в блоке
// тарифа). Флаг нужен, чтобы про одно повреждение сказать человеку один раз, а
// не двумя одинаковыми строками из разных мест.
$kartaMetodovSlomana = false;
if ($installed === true) {
    // Карта доступности лежит в том же сторе, и он бывает повреждён. Экран
    // состояния — последнее место, которое имеет право падать: человек приходит
    // сюда именно тогда, когда что-то сломалось. Читаем как всё остальное на этом
    // экране: сбой превращается в понятную строку, а не в пустой экран.
    try {
        $netMetodov = capMissingRequired();
        if ($netMetodov !== []) {
            $add('Портал не даёт вызвать методы, без которых работа невозможна: ' . implode(', ', $netMetodov),
                 'Права здесь ни при чём — проверьте на портале, включён ли нужный модуль и не старее ли '
                 . 'версия портала требуемой. На коробке это решает администратор портала, а не приложение', 'error');
        }
        $netNeobyaz = capMissing(capNeeded()['необязательные']);
        if ($netNeobyaz !== []) {
            $add('Часть возможностей недоступна: портал не даёт вызвать ' . implode(', ', $netNeobyaz),
                 'Остальное работает. Если эти возможности нужны — включите соответствующий модуль на портале');
        }
    } catch (Throwable $e) {
        $kartaMetodovSlomana = true;
        $add('Не удалось прочитать, какие методы портала доступны приложению',
             'Состояние неизвестно — это не значит «всё хорошо». Проверьте место на диске и права на каталог '
             . 'состояния, затем обновите экран', 'error');
    }
}

// ── Плейсменты: объявлено против того, что портал реально держит ─────────
$placements = ['объявлено' => [], 'привязано' => [], 'расхождение' => [], 'проверено' => false];
$placementExpected = [];
foreach (placementSpec() as $p) {
    $placements['объявлено'][] = $p['PLACEMENT'];
    $placementExpected[$p['PLACEMENT']] = $p['HANDLER'];
}
if ($installed === true && $placements['объявлено'] !== []) {
    try {
        $actual = placementsActual(b24());
        $placements['проверено'] = true;
        $placements['привязано'] = array_keys($actual);
        // Один совпавший код ничего не доказывает: после переезда портал может
        // держать старый HANDLER и открывать чужой стенд. Экран зелёный только
        // при точном совпадении и кода, и адреса.
        foreach ($placementExpected as $code => $handler) {
            if (!isset($actual[$code]) || !hash_equals($handler, (string)$actual[$code])) {
                $placements['расхождение'][] = $code;
            }
        }
        if ($placements['расхождение'] !== []) {
            $add('Не привязаны к текущему адресу приложения: ' . implode(', ', $placements['расхождение']),
                 'Нажмите «Пересобрать» ниже — приложение привяжет их заново');
        }
    } catch (StoreCorruptedException $e) {
        // Порча стора долетает сюда транзитом: перед каждым обращением к порталу
        // клиент спрашивает тариф (throttleByPlan → planRead). Пока этот случай
        // шёл общим Throwable, человек читал «временный сбой связи» и обновлял
        // страницу по кругу вместо того, чтобы спасать данные (находка K1-25).
        $add('Повреждено хранилище приложения — проверить вкладки и пункты меню не вышло',
             'Не сохраняйте новые данные поверх файла. Передайте разработчику quarantine-копию '
             . 'и время этой проверки', 'error');
    } catch (Throwable $e) {
        $add('Не удалось спросить портал о вкладках и пунктах меню',
             'Обычно это временный сбой связи — обновите страницу через минуту. '
             . 'Пока проверка не прошла, плейсменты не помечаются отсутствующими');
    }
}

// ── События портала ──────────────────────────────────────────────────────
// Приложение может выглядеть совершенно здоровым и при этом не получать ни
// одного события: подписка снимается порталом при обновлении приложения и
// молча не встаёт при нехватке прав. Поэтому «объявлено — подключено» стоит
// на видном месте, рядом с вкладками.
require_once __DIR__ . '/events-bind.php';
$events = ['объявлено' => count(eventsProjectSpec()), 'подключено' => 0, 'не_подключены' => [],
           'проверено' => false, 'уборка_при_удалении' => null];
// Спрашиваем портал и тогда, когда проект событиями не пользуется: служебная
// подписка на удаление приложения стоит всегда, и её пропажа означает, что
// после удаления с портала на диске останутся рабочие токены и список доступа.
if ($installed === true) {
    $eventsState = eventsHealth(b24());
    $events['подключено']    = $eventsState['connected'];
    $events['не_подключены'] = $eventsState['missing'];
    $events['проверено']     = $eventsState['status'] !== 'unknown';
    $events['уборка_при_удалении'] = $eventsState['cleanup_bound'] ?? null;
    if ($eventsState['missing'] !== []) {
        $add('Портал не шлёт события: ' . implode(', ', $eventsState['missing']),
             'Нажмите «Пересобрать привязки» на этом экране — подписка ставится заново без переустановки; '
             . 'если не помогло, переустановите приложение из карточки на портале');
    }
    if (($eventsState['cleanup_bound'] ?? null) === false) {
        $add('Приложение не узнает о своём удалении с портала',
             'Нажмите «Пересобрать привязки» на этом экране: без этой подписки после удаления на сервере '
             . 'останутся рабочие токены портала и список доступа, и они достанутся следующей установке');
    }
    if ($eventsState['status'] === 'unknown') {
        $add('Не удалось спросить портал о подписке на события',
             'Обычно это временный сбой связи — обновите страницу через минуту');
    }
}

// ── Фоновая обработка ────────────────────────────────────────────────────
// env.php проверяет state ещё до загрузки HTTP-гейта. Canonical health получает
// bounded snapshot, забирает его только ПОСЛЕ admin gate и не перечитывает файл:
// один ответ не смешивает два поколения state и GET не создаёт quarantine.
if (is_array($stateBootstrap) && ($stateBootstrap['status'] ?? '') === 'error') {
    $state = null;
    $stateProblem = [
        'too_large' => 'превышен безопасный предел размера',
        'unreadable' => 'файл сейчас недоступен для чтения',
        'corrupt' => 'содержимое не разбирается как состояние',
        'invalid' => 'файл имеет небезопасный формат',
    ][(string)($stateBootstrap['error'] ?? 'invalid')] ?? 'файл не прошёл безопасную проверку';
    $add('Повреждено хранилище «служебное состояние»: ' . $stateProblem
         . ' — данные не считаются пустыми',
         'Не сохраняйте новые данные поверх файла. Проверьте права и передайте разработчику исходный файл и время проверки',
         'error');
} elseif (is_array($stateBootstrap) && ($stateBootstrap['status'] ?? '') === 'valid') {
    $state = is_array($stateBootstrap['data'] ?? null) ? $stateBootstrap['data'] : [];
} elseif (is_array($stateBootstrap) && ($stateBootstrap['status'] ?? '') === 'missing') {
    $state = [];
} else {
    // Защитный fallback для CLI/include, где exact health entrypoint не доказан.
    $state = $readState(STATE_FILE, 'служебное состояние');
}
$cronAt = $state === null ? null : (string)($state['cron_last_run_at'] ?? '');
$cron = [
    'последний_запуск' => $cronAt,
    'успешно'          => $state === null ? null : (bool)($state['cron_last_ok'] ?? false),
    'длительность_мс'  => $state === null ? null : (int)($state['cron_last_ms'] ?? 0),
];
if ($state !== null && is_file(APP_PATH . '/bin/process.php')) {
    $cronTimestamp = appIsoTimestamp($cronAt);
    // Порог — час, а не сутки (ревью 23.09.2026, bezopasnost-1): доступ
    // заблокированного в портале сотрудника гасит ТОЛЬКО фон, а пропуск живёт
    // SESSION_TTL (8 часов). Тревога через сутки приходила на три срока пропуска
    // позже, чем обещание «доступ снимается за десять минут» перестало быть верным.
    if ($cronAt === '') {
        $add('Фоновая обработка ни разу не запускалась',
             'Пока фон не работает, пропуска заблокированных в портале сотрудников не гасятся до конца срока (до 8 часов). '
             . 'Проверьте, заведено ли задание в панели хостинга — команду печатает деплой');
    } elseif ($cronTimestamp === null) {
        $add('В состоянии фоновой обработки записано некорректное время последнего запуска',
             'Откройте вкладку «Журнал» и передайте разработчику время проверки: state нельзя считать достоверным', 'error');
    } elseif ($cronTimestamp < time() - 3600) {
        $add('Фоновая обработка не запускалась больше часа',
             'Пока фон молчит, пропуска заблокированных в портале сотрудников не гасятся до конца срока (до 8 часов). '
             . 'Проверьте задание планировщика в панели хостинга');
    } elseif (!$cron['успешно']) {
        $add('Последний фоновый прогон завершился ошибкой',
             'Откройте вкладку «Журнал» и посмотрите записи cron.fail');
    }
}

// ── События портала: очередь и ящик неразобранных ────────────────────────
require_once __DIR__ . '/queue.php';
$deadCount = null;
$queueCount = null;
try {
    $deadCount = queueDeadCount();
    $queueCount = queueSize();
} catch (StoreCorruptedException $e) {
    $add('Повреждено хранилище очереди событий — её размер и неразобранные события неизвестны',
         'Не запускайте replay до разбора quarantine-копии; передайте её разработчику', 'error');
} catch (Throwable $e) {
    $add('Очередь событий сейчас недоступна — её состояние неизвестно',
         'Проверьте права/место на диске и повторите проверку', 'error');
}
if ($deadCount !== null && $deadCount > 0) {
    $add('Событий, которые не удалось разобрать: ' . $deadCount,
         'Посмотрите записи event.deadletter в журнале, почините обработчик и верните события в работу '
         . 'командой php www/bin/process.php replay', 'error');
}

// ── Операции с неизвестным исходом ───────────────────────────────────────
// Процесс оборвался между самой работой и записью «сделано»: могло записаться в
// портал, могло нет. Повторять вслепую нельзя (второй счёт, второй перевод), но
// и молчать нельзя — иначе задача просто зависает, и это никому не видно.
$ops = $readState(OPS_FILE, 'операции с внешним эффектом');
$unknownOps = [];
if ($ops !== null) {
    foreach ($ops as $key => $rec) {
        if (is_array($rec) && ($rec['status'] ?? '') === 'unknown') $unknownOps[] = (string)$key;
    }
}
if ($unknownOps !== []) {
    // Совет обязан быть ИСПОЛНИМЫМ. Раньше здесь стояло «повторите действие» — но
    // повтор с тем же ключом ничего не делает: ключ занят статусом «неизвестно», и
    // снять его умела только командная строка сервера, которой у администратора
    // портала нет. Теперь рядом с проблемой едут сами ключи, и экран показывает
    // кнопку «Снять» (POST api/ops.php) — после проверки в портале.
    $add('Операции с неизвестным исходом: ' . implode(', ', array_slice($unknownOps, 0, 5))
         . (count($unknownOps) > 5 ? ' и ещё ' . (count($unknownOps) - 5) : ''),
         'Откройте портал и посмотрите, выполнено ли это на самом деле. Затем нажмите «Снять» '
         . 'у нужной операции — и, если работа не сделана, повторите действие. Пока ключ не снят, '
         . 'приложение не повторит операцию само, чтобы не сделать её дважды', 'error');
}

// ── Последние ошибки: чтобы не идти за ними в журнал ─────────────────────
// ЧИТАЕМ ПОД ЗАЩИТОЙ, как и все остальные обращения к диску на этом экране.
// Журнал живёт в каталоге, которого может не быть: его сносит чужая уборка,
// подменяет обычный файл, кончается место, не хватает прав на создание. Тогда
// journalQuery → journalFile() → storeEnsureDir() бросает, и голый вызов
// превращал ВЕСЬ экран в пустой 500 — единственный эндпоинт приложения,
// который ломался в тех условиях, ради которых его и открывают (K4-12, круг 4).
// Пустой список ошибок при этом выдавать за «ошибок нет» нельзя: помечаем
// выборку неполной тем же признаком truncated, что и при битых строках.
$lastErrors = [];
$errorScan = ['rows' => [], 'scanned' => 0, 'truncated' => false];
$journalUnavailable = false;
try {
    $errorScan = journalQuery(['level' => 'error', 'limit' => 5,
        // Ошибки ЭТОГО портала: текущей регистрации и прежних на той же
        // площадке. Одно текущее поколение опустошало блок ровно после
        // переустановки — то есть в момент, когда за ним и приходят, — а
        // вкладка «Журнал» те же строки показывала (K4-29, круг 4). Набор
        // поколений обе стороны берут одной функцией, а не собирают на месте.
        'install_generation' => appInstallGenerationsOfThisPortal($tokens)]);
} catch (StoreCorruptedException $e) {
    $journalUnavailable = true;
    $add('Журнал приложения сейчас недоступен: его хранилище повреждено — последние ошибки показать не удалось',
         'Остальные проверки на этом экране достоверны. Передайте разработчику quarantine-копию журнала '
         . 'и время этой проверки; вкладка «Журнал» до разбора работать не будет', 'error');
} catch (Throwable $e) {
    $journalUnavailable = true;
    $add('Журнал приложения сейчас недоступен — последние ошибки показать не удалось',
         'Остальные проверки на этом экране достоверны. Проверьте каталог data/' . LOG_DIR_NAME
         . ' на сервере: он должен быть каталогом с правом записи, а не файлом; '
         . 'посмотрите свободное место и обновите экран', 'error');
}
foreach ($errorScan['rows'] as $r) {
    $lastErrors[] = [
        'когда'  => (string)($r['ts'] ?? ''),
        'что'    => (string)($r['event'] ?? ''),
        'текст'  => (string)($r['msg'] ?? ''),
        'код_обращения' => (string)($r['ref'] ?? ''),
    ];
}
$journalTruncated = $journalUnavailable || !empty($errorScan['truncated']);
// Совет «откройте раздел Журнал» уместен, только когда журнал ЧИТАЕТСЯ. Если он
// недоступен целиком, причина уже названа выше строкой с исполнимым действием —
// второй совет отправлял бы человека туда, где его ждёт тот же отказ.
if ($journalTruncated && !$journalUnavailable) {
    $add('Журнал ошибок прочитан не полностью',
         'Откройте раздел «Журнал» и сообщите разработчику: часть строк '
         . 'повреждена или превышен безопасный предел чтения', 'warn');
}

// ТАРИФ ПОРТАЛА. Показываем прямо на экране состояния: от него зависит, с какой
// частотой приложение вправе обращаться к порталу, и человек должен видеть,
// знаем ли мы тариф вообще (неизвестный = работаем по самому строгому пределу).
// Тот же спрос, что и выше: экран состояния не имеет права падать из-за того,
// что повреждено одно из хранилищ. Не прочитали — говорим это словами, а не
// показываем пустые поля, которые читаются как «всё в порядке».
try {
    $plan = planRead();
} catch (Throwable $e) {
    $plan = [];
    $add('Не удалось прочитать сведения о тарифе портала и темпе запросов',
         'Показанные ниже пределы неизвестны, а не «по умолчанию». Проверьте каталог состояния и обновите экран', 'error');
}
// Те же две строчки про методы, но для карточки тарифа. Читаем ПОД защитой:
// это последние обращения к стору на экране, и до правки они роняли весь экран
// в 500 при повреждённом data/capability.php — человек терял и остальные девять
// диагнозов, ради которых сюда и пришёл (находка ревью K1-25).
try {
    $metodyNedostupny = capMissing(array_merge(
        capNeeded()['обязательные'], capNeeded()['необязательные']));
    $metodySlovami = capHuman();
} catch (Throwable $e) {
    $metodyNedostupny = [];
    $metodySlovami = 'доступность методов портала неизвестна — карта не прочитана';
    if (!$kartaMetodovSlomana) {
        $kartaMetodovSlomana = true;
        $add('Не удалось прочитать, какие методы портала доступны приложению',
             'Состояние неизвестно — это не значит «всё хорошо». Проверьте место на диске и права на каталог '
             . 'состояния, затем обновите экран', 'error');
    }
}
$planVid = [
    'тариф'          => (string)($plan['license'] ?? ''),
    'энтерпрайз'     => !empty($plan['enterprise']),
    'коробка'        => !empty($plan['box']),
    'запросов_в_сек' => planRatePerSecond($plan),
    // ОТКУДА ЧИСЛО. Без этого поля осторожная догадка о коробке читается с
    // экрана как серверный факт: «предел 5 запросов в секунду» — и человек
    // принимает по ней решения о нагрузке. Здесь честно: `plan` — предел
    // портала, `configured` — измерено и задано человеком, `fallback` — ёмкость
    // неизвестна, идём осторожно.
    'откуда_предел'  => planRateSource($plan),
    // ЧТО ИМЕННО НЕДОСТУПНО. Право выдано ≠ метод работает: на коробке модуль
    // бывает выключен, а версия портала старее. Без этой строки человек ищет
    // причину в правах, которых у него как раз достаточно.
    'методы_недоступны' => $metodyNedostupny,
    'методы_словами' => $metodySlovami,
    'корзина'        => planBucket($plan),
    'определён'      => (int)($plan['at'] ?? 0) > 0 ? date('c', (int)$plan['at']) : '',
    'словами'        => planHuman($plan),
];

apiOk([
    'portal'      => $portal,
    'план'        => $planVid,
    'owner'       => ['uid' => $ownerUid, 'сотрудников_в_доступе' => count($acl['users'] ?? [])],
    'scopes'      => ['нужны' => $needed, 'выданы' => $granted, 'не_хватает' => $missing],
    'placements'  => $placements,
    'events'      => $events,
    'cron'        => $cron,
    'события'     => ['в_очереди' => $queueCount, 'не_разобрано' => $deadCount],
    'app_token'   => $hasAppToken,
    'last_errors' => $lastErrors,
    'journal'     => ['scanned' => (int)($errorScan['scanned'] ?? 0), 'truncated' => $journalTruncated],
    // Ключи зависших операций отдаём отдельным полем: по ним экран рисует кнопку
    // «Снять». В тексте проблемы они тоже есть, но текст — для человека, а это —
    // для кнопки, и разбирать строку фронту незачем.
    'stuck_ops'   => $unknownOps,
    'problems'    => $problems,
    'app_url'     => APP_URL,
]);
