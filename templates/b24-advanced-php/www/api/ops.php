<?php
declare(strict_types=1);
/**
 * api/ops.php — снять залипшую операцию с неизвестным исходом.
 *
 * POST {key: "<ключ операции>"} → {ok:true, key:"…"}
 *
 * ЗАЧЕМ. Операция с внешним эффектом (создать сделку, списать деньги) идёт через
 * runOnce(): ключ занимается ДО работы и закрывается после. Если процесс оборвался
 * между работой и записью «сделано», ключ остаётся со статусом `unknown` — портал
 * мог сделать, мог нет. Автоматически повторять такое нельзя (второй счёт, второй
 * перевод), поэтому ключ живёт до решения ЧЕЛОВЕКА.
 *
 * Решение человек принимает так: открывает портал, смотрит, выполнено ли на самом
 * деле, и снимает ключ. Дальше повтор действия либо нужен, либо нет — но это уже
 * его осознанный выбор, а не догадка приложения.
 *
 * Раньше снять ключ можно было ТОЛЬКО из командной строки сервера
 * (`php www/bin/process.php forget-once <ключ>`), а экран «Состояние» при этом
 * советовал «повторите действие». Администратор портала командной строки не имеет:
 * совет был неисполним, операция висела вечно, а вместе с ней рос и файл журнала
 * операций — до предела, на котором отказывают уже ВСЕ мутации.
 *
 * Роль — admin: снятие ключа снимает и защиту от повторного внешнего эффекта.
 */

require_once __DIR__ . '/http.php';
require_once __DIR__ . '/access.php';

installFailureHandler(true);

$ctx = apiBoot(['methods' => ['POST'], 'role' => 'admin']);

$body = apiBody();
$key  = trim((string)($body['key'] ?? ''));
if ($key === '') apiFail('Не указан ключ операции', 400, 'key_required');

try {
    // Тот же предел, что у мутаций runOnce: этот endpoint тоже декодирует файл
    // целиком, поэтому без preflight сам экран исправления мог упасть по памяти.
    // Admin recovery должен разбирать тот же увеличенный предел, что cron-prune;
    // иначе переполненный running/unknown журнал нельзя снять именно тогда,
    // когда мутации уже остановлены обычным 2 MiB ceiling.
    runOnceAssertFileWithinByteLimit(RUN_ONCE_MAX_BYTES * 8);
} catch (RuntimeException $e) {
    apiFail('Журнал операций слишком велик для безопасного чтения. Дождитесь фоновой уборки '
        . 'или запустите php www/bin/process.php на сервере', 503, 'ops_too_large');
}

$ops = storeRead(OPS_FILE) ?? [];
$rec = is_array($ops[$key] ?? null) ? $ops[$key] : null;
if ($rec === null) {
    // Уже сняли (соседняя вкладка, крон) — это не ошибка, экран просто отстал.
    apiOk(['key' => $key, 'note' => 'Такой операции уже нет — экран обновится.']);
}

$status = (string)($rec['status'] ?? '');
if ($status !== 'unknown') {
    // Идущую операцию снимать нельзя: её callback прямо сейчас работает с
    // порталом, и снятие ключа открыло бы дорогу второму такому же вызову.
    apiFail('Снять можно только операцию с неизвестным исходом. Эта сейчас в состоянии «'
        . $status . '» — дождитесь её завершения', 409, 'not_unknown');
}

try {
    // Снимаем ИМЕННО ту запись, которую прочитали выше и по которой отвечали
    // человеку «эта операция с неизвестным исходом». Между чтением и снятием
    // ключ успевает уйти и вернуться: его сняли из командной строки, операция
    // прошла заново и записала «сделано». Безусловное снятие стирало это
    // «сделано» — единственное доказательство, что внешний эффект уже был, — и
    // следующий вызов повторял его (находка ревью R3-002 от 09.08.2026).
    runOnceForget($key, $rec);
} catch (RunOnceStaleForgetException $e) {
    // Отказ, который лечится обновлением экрана: перечитанная запись даст новое
    // решение — снимать её или уже нечего.
    apiFail('Состояние операции изменилось, пока экран был открыт, — снятие отменено, '
        . 'чтобы не стереть уже записанный исход. Обновите экран и посмотрите заново',
        409, 'version_conflict');
} catch (Throwable $e) {
    // Аренда занята — процесс операции ожил и работает. Это ответ, а не сбой.
    apiFail('Операция снова выполняется — снимать её ключ нельзя. Обновите экран через минуту',
        409, 'operation_running');
}

// Аудит обязателен: человек своей рукой снял защиту от повторного внешнего
// эффекта, и по журналу должно быть видно, кто и когда это сделал.
auditLog('ops.forget', ['ключ' => $key, 'исход_был' => $status], $ctx['uid']);

apiOk(['key' => $key]);
