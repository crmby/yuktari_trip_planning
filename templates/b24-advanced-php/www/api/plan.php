/**
 * ТАРИФ ПОРТАЛА И ЛИМИТ ИНТЕНСИВНОСТИ ЗАПРОСОВ.
 *
 * ЗАЧЕМ. Портал ограничивает не объём данных, а ЧАСТОТУ обращений, и пороги
 * зависят от тарифа. Официальные цифры (limits.md, раздел «Ограничения на
 * интенсивность запросов»):
 *
 *     Энтерпрайз — 5 запросов в секунду, корзина до блокировки 250
 *     Прочие     — 2 запроса в секунду, корзина до блокировки 50
 *
 * Приложение, написанное «на глаз», ведёт себя одинаково на обоих: на обычном
 * тарифе оно упирается в `QUERY_LIMIT_EXCEEDED` и теряет половину обхода, а на
 * Энтерпрайзе — работает вдвое медленнее, чем позволено, и выгрузка, которая
 * могла занять час, идёт три. Поэтому тариф спрашивается у самого портала и
 * запоминается, а темп считается по нему.
 *
 * ОТКУДА ЦИФРА. Метод `app.info` отдаёт `LICENSE` (например `ru_ent10000`),
 * `LICENSE_TYPE` (`ent10000`) и `LICENSE_FAMILY` (`ent`). Семейство `ent` — это
 * Энтерпрайз. К коробочному порталу не применяется облачная leaky-bucket корзина
 * интенсивности X/Y. Это не обещание безлимитности: ёмкость задаёт сервер, а REST
 * resource guard по умолчанию выключен, но может быть включён администратором.
 *
 * НЕИЗВЕСТНЫЙ ТАРИФ — САМЫЙ СТРОГИЙ. Портал не ответил, ответ непонятен, метод
 * недоступен — берём 2 запроса в секунду. Ошибиться в эту сторону значит
 * работать медленнее; ошибиться в другую — получить блокировку метода и
 * потерянные данные, причём у клиента, а не у нас.
 *
 * ПОЧЕМУ ЭТО НЕ ЗАМЕНЯЕТ ПАКЕТЫ. Лимит считает HTTP-запросы, а не записи.
 * Пакет из 50 команд — это ОДИН HTTP-запрос для облачной корзины. Пакеты не отменяют
 * ресурсную стоимость команд, REST resource guard и ёмкость сервера; эти ограничения отдельны.
 */

/** Пороги интенсивности по документации портала (limits.md). */
if (!defined('PLAN_RATE_ENTERPRISE')) define('PLAN_RATE_ENTERPRISE', 5.0);   // запросов в секунду
if (!defined('PLAN_RATE_DEFAULT'))    define('PLAN_RATE_DEFAULT', 2.0);
if (!defined('PLAN_BUCKET_ENTERPRISE')) define('PLAN_BUCKET_ENTERPRISE', 250); // корзина до блокировки
if (!defined('PLAN_BUCKET_DEFAULT'))    define('PLAN_BUCKET_DEFAULT', 50);
/** Как часто переспрашивать тариф. Тариф меняют редко, но меняют. */
if (!defined('PLAN_TTL_SEC')) define('PLAN_TTL_SEC', 86400);

/**
 * Разобрать ответ `app.info` в понятный вид.
 *
 * Определяем Энтерпрайз по СЕМЕЙСТВУ (`LICENSE_FAMILY = ent`), а если его нет —
 * по идентификатору тарифа (`ent250`, `ent10000`). По полному `LICENSE`
 * ориентироваться нельзя вслепую: там префикс региона (`ru_`, `de_`), и у
 * тарифов, менявших состав, публичное имя не отражает содержимое.
 *
 * @param array $info ответ метода app.info (поле result)
 * @return array{license:string,type:string,family:string,enterprise:bool,box:bool}
 */
function planParseAppInfo(array $info): array {
    $license = trim((string)($info['LICENSE'] ?? ''));
    $type    = strtolower(trim((string)($info['LICENSE_TYPE'] ?? '')));
    $family  = strtolower(trim((string)($info['LICENSE_FAMILY'] ?? '')));

    // ТИП ПОРТАЛА: сначала слово оператора, потом догадка по лицензии.
    //
    // Прежде коробка распознавалась ТОЛЬКО по строкам `selfhosted` в ответе
    // `app.info` — а документация портала таких значений не обещает (находка
    // ревью 08.08.2026, BXREV-020). Не совпало написание — коробка молча
    // считалась облаком: измеренная оператором ёмкость игнорировалась, темп
    // падал до облачного, а экран уверенно называл тип портала. Догадка,
    // выданная за факт, — худшее, что может сделать такой механизм.
    //
    // Поэтому у типа портала теперь есть ИСТОЧНИК:
    //   configured — оператор сказал прямо (BXAPP_PORTAL_KIND=box|cloud);
    //   license    — узнали по ответу портала;
    //   unknown    — не знаем; работаем осторожно и говорим об этом вслух.
    $zadano = strtolower(trim((string)(getenv('BXAPP_PORTAL_KIND') ?: '')));
    $poLicenzii = $family === 'selfhosted' || strpos($type, 'selfhosted') !== false
        || strpos(strtolower($license), 'selfhosted') !== false;
    $oblakoPoLicenzii = $family === 'ent' || $family === 'company' || $family === 'crm'
        || $type !== '' || $license !== '';

    if ($zadano === 'box' || $zadano === 'cloud') {
        $box = ($zadano === 'box');
        $istochnikTipa = 'configured';
    } elseif ($poLicenzii) {
        $box = true;
        $istochnikTipa = 'license';
    } elseif ($oblakoPoLicenzii) {
        $box = false;
        $istochnikTipa = 'license';
    } else {
        // Портал ответил, но ничего похожего на тип не сказал. Это НЕ облако.
        $box = false;
        $istochnikTipa = 'unknown';
    }

    $enterprise = $family === 'ent' || preg_match('~(^|_)ent\d*$~', $type) === 1;
    return [
        'license'    => $license,
        'type'       => $type,
        'family'     => $family,
        'enterprise' => (bool)$enterprise,
        'box'        => (bool)$box,
        'тип_откуда' => $istochnikTipa,
    ];
}

/** Откуда известен тип портала: configured · license · unknown. */
function planKindSource(array $plan): string {
    $s = (string)($plan['тип_откуда'] ?? '');
    return in_array($s, ['configured', 'license', 'unknown'], true) ? $s : 'unknown';
}

/**
 * Заданный настройкой темп — сколько запросов в секунду разрешил человек.
 *
 * Нужен для коробки, где облачная корзина интенсивности не применяется: темп выбирают
 * по замеру серверной ёмкости. Эта настройка не описывает и не отменяет REST resource guard. Облачные
 * пороги настройкой не перебиваются: там ограничение
 * ставит портал, и «разрешить себе больше» означает получить блокировку.
 *
 * @return float 0 — настройки нет или она бессмысленна
 */
function planConfiguredRate(): float {
    $raw = getenv('BXAPP_RATE_PER_SEC');
    if ($raw === false || trim((string)$raw) === '') return 0.0;
    $v = (float)$raw;
    // Ноль и отрицательное — это не «медленнее», это остановка приложения.
    return $v > 0 ? $v : 0.0;
}

/**
 * Сколько запросов в секунду можно этому порталу.
 *
 * ОБЛАКО. Предел ставит портал, он известен из документации и зависит от тарифа.
 *
 * КОРОБКА. Облачная leaky-bucket корзина интенсивности не применяется. Серверная ёмкость и
 * включаемый администратором REST resource guard остаются отдельными ограничениями.
 * Раньше здесь стояли «энтерпрайзовые» 5 запросов в секунду, и это была выдумка
 * в обе стороны: мощную коробку мы искусственно душили, слабую — заваливали, а
 * человек видел выдуманное число на экране «Состояние» как серверный факт.
 * Теперь без настройки берётся самый осторожный бюджет, а настоящая ёмкость
 * задаётся `BXAPP_RATE_PER_SEC` — после измерения на конкретной коробке.
 *
 * @param array $plan сохранённый тариф (см. planRead)
 */
function planRatePerSecond(array $plan): float {
    // Настройку оператора принимаем и тогда, когда тип портала НЕ ОПОЗНАН:
    // человек, который померил ёмкость своего сервера, знает о нём больше, чем
    // наша догадка по строке лицензии. На облаке настройка по-прежнему не
    // действует — там предел ставит портал, и «разрешить себе больше» означает
    // получить блокировку (об этом говорит planHuman).
    if (!empty($plan['box']) || planKindSource($plan) === 'unknown') {
        $zadano = planConfiguredRate();
        return $zadano > 0 ? $zadano : PLAN_RATE_DEFAULT;
    }
    return !empty($plan['enterprise']) ? PLAN_RATE_ENTERPRISE : PLAN_RATE_DEFAULT;
}

/**
 * ОТКУДА ВЗЯЛОСЬ ЧИСЛО ТЕМПА. Три честных ответа, и ни одного «просто так»:
 *
 *   plan       — предел портала по тарифу (факт из документации);
 *   configured — задано человеком после измерения коробки;
 *   fallback   — ёмкость неизвестна, идём по самому осторожному бюджету.
 *
 * Источник показывается человеку и попадает в диагностику: догадка, выданная за
 * факт, — худшее, что может сделать такой механизм.
 */
function planRateSource(array $plan): string {
    if (!empty($plan['box']) || planKindSource($plan) === 'unknown') {
        return planConfiguredRate() > 0 ? 'configured' : 'fallback';
    }
    // Смотрим на САМ ТАРИФ, а не на отметку времени: разобранный ответ портала —
    // уже факт, даже если он ещё не лёг в состояние. Пусто — значит про портал
    // мы не знаем ничего и идём по осторожному бюджету.
    $izvesten = ($plan['license'] ?? '') !== '' || ($plan['family'] ?? '') !== ''
        || ($plan['type'] ?? '') !== '';
    return $izvesten ? 'plan' : 'fallback';
}

/**
 * Размер облачной leaky-bucket корзины интенсивности — для показа человеку и расчётов.
 * Для коробки 0 означает «не применимо», а не «без ограничений»; REST resource guard эта функция не проверяет.
 */
function planBucket(array $plan): int {
    if (!empty($plan['box'])) return 0;
    return !empty($plan['enterprise']) ? PLAN_BUCKET_ENTERPRISE : PLAN_BUCKET_DEFAULT;
}

/** Человеческое название режима — для экрана «Состояние». */
function planHuman(array $plan): string {
    if (($plan['at'] ?? 0) <= 0) return 'тариф ещё не спрашивали — темп по самому строгому лимиту';
    $otkuda = planKindSource($plan);
    $pripiska = $otkuda === 'configured' ? ' (тип портала задан настройкой BXAPP_PORTAL_KIND)' : '';
    if ($otkuda === 'unknown') {
        // Честно: тип портала мы НЕ определили. Прежде такой портал молча
        // назывался облачным, а измеренная оператором ёмкость игнорировалась.
        $zadano = planConfiguredRate();
        return 'тип портала не определён по ответу — идём осторожно '
            . ($zadano > 0 ? $zadano . ' запроса/с по настройке BXAPP_RATE_PER_SEC' : PLAN_RATE_DEFAULT . ' запроса/с')
            . '; если это коробка, скажите прямо: BXAPP_PORTAL_KIND=box (и BXAPP_RATE_PER_SEC — измеренная ёмкость)';
    }
    if (!empty($plan['box'])) {
        $zadano = planConfiguredRate();
        if ($zadano > 0) {
            return 'коробочный портал — ' . $zadano . ' запроса/с по настройке BXAPP_RATE_PER_SEC; '
                . 'облачная leaky-bucket корзина интенсивности не применяется; '
                . 'REST resource guard этим блоком не проверен' . $pripiska;
        }
        return 'коробочный портал — облачная leaky-bucket корзина интенсивности не применяется; '
            . 'ёмкость сервера не измерена; REST resource guard этим блоком не проверен; '
            . 'идём осторожно ' . PLAN_RATE_DEFAULT . ' запроса/с (задаётся настройкой BXAPP_RATE_PER_SEC)' . $pripiska;
    }
    // Облако: настройка темпа здесь НЕ действует. Молчать об этом нельзя —
    // человек её задал и вправе знать, что она ничего не меняет.
    if (planConfiguredRate() > 0) {
        return ($plan['license'] ?: 'облачный портал') . ' — '
            . ($plan['enterprise'] ? PLAN_RATE_ENTERPRISE : PLAN_RATE_DEFAULT) . ' запроса/с по пределу портала'
            . $pripiska . '; настройка BXAPP_RATE_PER_SEC на облаке НЕ действует — предел ставит портал';
    }
    if (!empty($plan['enterprise'])) {
        return 'Энтерпрайз (' . ($plan['license'] ?: 'ent') . ') — '
            . PLAN_RATE_ENTERPRISE . ' запроса/с, корзина ' . PLAN_BUCKET_ENTERPRISE;
    }
    return ($plan['license'] ?: 'обычный тариф') . ' — '
        . PLAN_RATE_DEFAULT . ' запроса/с, корзина ' . PLAN_BUCKET_DEFAULT;
}

/** Прочитать сохранённый тариф. Пусто — ещё не спрашивали. */
function planRead(): array {
    $d = storeRead(PLAN_FILE);
    return is_array($d) ? $d : [];
}

/** Устарел ли сохранённый тариф. */
function planStale(array $plan): bool {
    $at = (int)($plan['at'] ?? 0);
    return $at <= 0 || (time() - $at) >= PLAN_TTL_SEC;
}

/**
 * Сохранить результат замера, только если после его начала не стартовал более
 * свежий. Сетевые ответы приходят не по порядку: старый медленный app.info не
 * имеет права затереть ответ запроса, начатого позже.
 */
function planPersistFreshest(array $candidate, float $startedAt): array {
    $candidate['refresh_started_at'] = $startedAt;
    return storeUpdate(PLAN_FILE, static function (array $prev) use ($candidate, $startedAt): array {
        $prevStartedAt = (float)($prev['refresh_started_at'] ?? 0.0);
        return $prevStartedAt > $startedAt ? $prev : $candidate;
    });
}

/**
 * Спросить тариф у портала и запомнить.
 *
 * ПРИ ОТКАЗЕ НЕ ПАДАЕМ и НЕ ЗАТИРАЕМ прежнее знание: приложение обязано
 * работать и без тарифа — просто по самому строгому лимиту. Возвращаем то, что
 * знаем сейчас.
 *
 * @param B24  $b24
 * @param bool $force спросить, не глядя на срок
 */
function planRefresh(B24 $b24, bool $force = false): array {
    $plan = planRead();
    if (!$force && !planStale($plan)) return $plan;

    $startedAt = microtime(true);
    $res = $b24->call('app.info');
    $info = is_array($res['result'] ?? null) ? $res['result'] : null;
    if ($info === null || !empty($res['error'])) {
        // Ответа нет — оставляем прежнее знание (или пустоту) и говорим об этом
        // в журнале один раз, а не при каждом запросе.
        if ($plan === []) {
            logAppError('тариф портала не определён: ' . (string)($res['error'] ?? 'ответ без result')
                . ' — работаем по самому строгому лимиту ' . PLAN_RATE_DEFAULT . ' запроса/с');
        }
        return $plan;
    }

    $razobrano = planParseAppInfo($info);
    $razobrano['at'] = time();
    $saved = planPersistFreshest($razobrano, $startedAt);
    appLog('info', 'plan.refresh', [
        'тариф'   => $saved['license'] ?? '',
        'семейство' => $saved['family'] ?? '',
        'энтерпрайз' => !empty($saved['enterprise']),
    ], ['msg' => 'тариф портала определён: ' . planHuman($saved)]);
    return $saved;
}

/** Потолок одного ожидания в ВЕБ-запросе. Дольше держать человека нельзя. */
if (!defined('PLAN_WAIT_CAP')) define('PLAN_WAIT_CAP', 0.5);
/**
 * Потолок одного ожидания в фоне (cron, консоль).
 *
 * Отдельный и заметно больший: воркер никого не держит, а темп для него важнее
 * скорости. С общим потолком в полсекунды шесть процессов по три запроса при
 * пределе 2 запроса в секунду укладывались в 2 секунды вместо 8,5 — то есть
 * общий темп не соблюдался вовсе (находка ревью 08.08.2026).
 */
if (!defined('PLAN_WAIT_CAP_CLI')) define('PLAN_WAIT_CAP_CLI', 5.0);
/** Сколько ждать своей очереди к общей отметке, прежде чем работать без неё. */
if (!defined('PLAN_GATE_WAIT')) define('PLAN_GATE_WAIT', 0.6);

/** Потолок ожидания для текущего контекста: человек ждёт иначе, чем крон. */
function planWaitCap(): float {
    return PHP_SAPI === 'cli' ? (float)PLAN_WAIT_CAP_CLI : (float)PLAN_WAIT_CAP;
}

/**
 * Самый БОЛЬШОЙ потолок ожидания в приложении — глубина законной очереди.
 *
 * Очередь общая, а терпение у процессов разное: крон готов ждать 5 секунд, веб —
 * полсекунды. Значит законную отметку в будущее выставляет самый терпеливый, и
 * судить «не переведены ли часы» своим потолком нельзя: веб-запрос принимал
 * честную очередь крона (now+1…now+5) за сбой, обнулял её и пускал всех разом —
 * то есть ровно тот залп, от которого очередь и защищает (находка ревью
 * 09.08.2026). Порог считаем по максимуму, а решение «ждать ли мне» — по своему.
 */
function planWaitCapMax(): float {
    return max((float)PLAN_WAIT_CAP, (float)PLAN_WAIT_CAP_CLI);
}

/**
 * Занимать ли слот в общей очереди — ЧИСТОЕ решение, без файлов и часов.
 *
 * Вынесено из мутатора состояния намеренно: внутри замыкания под замком это
 * нельзя было проверить иначе как текстом кода, а роль у двух потолков разная и
 * перепутать их легко (что и случилось — находка ревью 09.08.2026):
 *   $potolok    — СКОЛЬКО ЖДЁТ ЭТОТ процесс (веб полсекунды, крон пять секунд);
 *   $potolokMax — какая глубина очереди вообще ЗАКОННА в приложении. Отметка
 *                 дальше неё означает переведённые часы или состояние с чужой
 *                 машины, и только её можно сбрасывать.
 *
 * @return array{момент: float, сброшено: bool} момент 0.0 — слот не занят
 */
function planSlotDecide(float $last, float $now, float $interval,
                        float $potolok, float $potolokMax): array {
    $sbros = false;
    if ($last > $now + $potolokMax + $interval) { $last = 0.0; $sbros = true; }
    $slot = $last > 0.0 ? max($now, $last + $interval) : $now;
    // Очередь глубже, чем ЭТОТ процесс вправе ждать: слот не занимаем — занятый
    // и брошенный слот сдвинул бы очередь всем остальным впустую.
    if (($slot - $now) > $potolok) return ['момент' => 0.0, 'сброшено' => $sbros];
    return ['момент' => $slot, 'сброшено' => $sbros];
}

/**
 * Сказать вслух, что общий темп сейчас НЕ соблюдается.
 *
 * Прежде отказ общей очереди был молчаливым: процесс тихо переходил на свой
 * счётчик, и приложение вдвоём-втроём превышало предел портала, а в журнале не
 * оставалось ни строки. Пишем не чаще раза в минуту на процесс — иначе под
 * нагрузкой журнал заполнит сама диагностика.
 */
function planNoteDegraded(string $prichina): void {
    static $kogda = 0.0;
    $now = microtime(true);
    if ($kogda > 0.0 && ($now - $kogda) < 60.0) return;
    $kogda = $now;
    if (!function_exists('appLog')) return;
    appLog('warn', 'plan.rate.degraded', ['причина' => $prichina, 'контекст' => PHP_SAPI],
        ['msg' => 'общий темп запросов к порталу не соблюдается: ' . $prichina
            . ' — процесс держит темп только внутри себя']);
}

/**
 * ОБЩАЯ ОЧЕРЕДЬ К ПОРТАЛУ — одна на все процессы приложения.
 *
 * ЗАЧЕМ. Предел портала считает запросы ПРИЛОЖЕНИЯ, а не процесса. На хостинге
 * разом живут веб-запрос, фоновый обработчик и воркер по расписанию; пока каждый
 * держал свой счётчик в памяти процесса, приложение втроём превышало предел
 * втрое — и получало блокировку у клиента, где отладить это труднее всего.
 *
 * КАК. Под эксклюзивным `flock` процесс РЕЗЕРВИРУЕТ себе будущий момент —
 * `max(сейчас, прошлый + интервал)` — и сразу отпускает замок. Ждёт он уже
 * снаружи, до своего момента.
 *
 * ПОЧЕМУ НЕ СПАТЬ ПОД ЗАМКОМ, как было раньше. Сон внутри блокировки делает
 * длину замка равной длине паузы: очередь мгновенно перерастает предохранитель
 * `PLAN_GATE_WAIT`, и все, кто не дождался, уходят «каждый сам за себя» — то
 * есть ровно в тот залп, от которого очередь и заведена. Замер ревью 08.08.2026:
 * шесть процессов по три запроса при пределе 2 запроса в секунду уложились в
 * 2,07 секунды вместо положенных 8,5. С резервированием замок держится
 * микросекунды, а ждут все параллельно и каждый своё.
 *
 * ПРЕДОХРАНИТЕЛЬ. Ждать своего момента дольше потолка (`planWaitCap()`) нельзя:
 * в вебе это человек перед пустым экраном. Такой процесс слот НЕ занимает,
 * отдаёт false и ГРОМКО отмечает это в журнале (`planNoteDegraded`) — прежде
 * переход на «каждый сам себе» был молчаливым и выглядел как исправная работа.
 *
 * ЦЕЛОСТНОСТЬ. Файл крошечный и пишется одним `fwrite` под блокировкой. Обрыв в
 * этот момент оставит его пустым — это читается как «отметки нет», и следующий
 * запрос просто пройдёт без задержки. Потерять здесь нечего: данных в файле нет,
 * только время.
 *
 * @return bool отработала ли общая очередь (false — зовущий делает своё ожидание)
 */
function planWaitTurn(float $interval): bool {
    if ($interval <= 0 || !defined('RATE_FILE') || !function_exists('storeUpdate')) return false;
    // Момент, который мы себе заняли. Ноль — не заняли ничего (см. ниже).
    $moment = 0.0;
    try {
        // Идём через общий механизм состояния, а не своим чтением файла: он уже
        // держит эксклюзивный замок на время правки, пишет с защитным префиксом
        // и переживает уборку установки наравне с остальным состоянием. Своя
        // раскладка в том же каталоге ломала уборку: файл не разбирался как
        // состояние и уезжал в карантин при удалении приложения.
        $potolok = planWaitCap();
        // Порог «часы переведены» — по САМОМУ терпеливому процессу приложения, а
        // не по своему: см. planWaitCapMax().
        $potolokMax = planWaitCapMax();
        storeUpdate(RATE_FILE, static function (array $prev) use ($interval, $potolok, $potolokMax, &$moment): ?array {
            $reshenie = planSlotDecide((float)($prev['at'] ?? 0), microtime(true),
                $interval, $potolok, $potolokMax);
            $moment = $reshenie['момент'];
            if ($moment <= 0.0) return null;   // слот не занят — писать нечего
            $prev['at'] = $moment;
            return $prev;
        }, PLAN_GATE_WAIT);
    } catch (Throwable $e) {
        // Замок занят дольше предохранителя или состояние недоступно. Падать
        // нельзя: темп страхует от блокировки у клиента, но сам не должен
        // становиться отказом обслуживания. Зовущий подстрахуется внутри своего
        // процесса — и это теперь видно в журнале, а не только по поведению.
        planNoteDegraded('общая отметка недоступна: ' . (function_exists('maskSecrets')
            ? (string)maskSecrets($e->getMessage()) : 'ошибка состояния'));
        return false;
    }

    if ($moment <= 0.0) {
        planNoteDegraded('очередь к порталу глубже потолка ожидания ('
            . number_format(planWaitCap(), 2, '.', '') . ' с)');
        return false;
    }

    // Ждём СНАРУЖИ замка: пока мы спим, соседи занимают следующие моменты и
    // спят параллельно. Именно это и даёт общий ровный темп вместо очереди из
    // процессов, каждый из которых ждёт ещё и чужой сон.
    $zhdat = $moment - microtime(true);
    if ($zhdat > 0) usleep((int)($zhdat * 1000000));
    return true;
}

/**
 * Текущий предел темпа для клиента портала.
 *
 * Отдельной функцией, потому что её зовут из клиента на КАЖДОМ запросе: она
 * обязана быть дешёвой и никогда не ходить в сеть.
 */
function planCurrentRate(): float {
    static $kesh = null;
    static $kogda = 0;
    // Читаем состояние не чаще раза в 5 секунд: файл маленький, но на обходе в
    // тысячи запросов лишние чтения заметны.
    if ($kesh === null || (time() - $kogda) > 5) {
        $kesh = planRatePerSecond(planRead());
        $kogda = time();
    }
    return (float)$kesh;
}
