/**
 * Высота окна приложения внутри портала.
 *
 * Зачем. Портал показывает приложение в iframe фиксированной высоты (в
 * плейсментах это ~200 px), поэтому без подгонки человек видит обрезанный экран
 * с внутренней полосой прокрутки, а под контентом — пустую белую полосу.
 * Штатный BX24.fitWindow() растягивает окно на всю страницу и в карточке сделки
 * выглядит сломанным, поэтому просим ровно ту высоту, которая нужна.
 *
 * Написано в восьми проектах заново — значит, место ему в шаблоне.
 */
(function (global) {
  'use strict';

  var FLOOR = 320;           // абсолютный минимум: ниже окно выглядит схлопнутым
  var MAX_HEIGHT = 3000;     // портал всё равно обрежет, но пусть будет предел
  var lastSent = 0;
  var timer = null;

  /**
   * ВЫСОТА КОНТЕЙНЕРА, КОТОРЫЙ ВЫДЕЛИЛ ПОРТАЛ.
   *
   * Замеряем ОДИН раз при загрузке — до того, как сами что-то попросили: тогда
   * innerHeight и есть та область, которую портал отвёл приложению. Ниже неё
   * ужиматься нельзя: окно становится короче контейнера, и снизу проступает
   * рабочий стол Битрикса — приложение выглядит обрезанным по нижнему краю.
   * (Ровно на это жаловался владелец: «окно ужато под контент и стало ниже
   * контейнера маркетплейса».)
   *
   * Больше — можно: длинный список честно растит окно.
   */
  // UI-геометрия: высота окна в пикселях.
  var frameFloor = Math.max(FLOOR, Math.round(global.innerHeight || 0) || FLOOR);

  /**
   * Высота ФАКТИЧЕСКОГО содержимого.
   *
   * Берём нижнюю границу последнего видимого элемента, а не scrollHeight
   * документа: scrollHeight помнит прежний размер окна, если у страницы есть
   * хоть одно правило вида min-height:100vh или height:100% — а внутри портала
   * vh это и есть высота окна, которую мы сами же и заказали. Из-за этого окно
   * переставало сжиматься: содержимое стало короче, а под ним осталась белая
   * полоса на пол-экрана.
   */
  function contentHeight() {
    var b = document.body;
    var bottom = 0;
    var kids = b.children;
    for (var i = 0; i < kids.length; i++) {
      var el = kids[i];
      if (el.id === 'toasts') continue;               // всплывает поверх, высоты не даёт
      var r = el.getBoundingClientRect();
      if (r.height <= 0) continue;
      bottom = Math.max(bottom, r.bottom + (global.scrollY || 0));
    }
    // Запасной вариант — прежний расчёт: пустой body лучше показать коротким,
    // чем нулевым.
    if (bottom <= 0) {
      var d = document.documentElement;
      bottom = Math.max(b.scrollHeight, b.offsetHeight, d.scrollHeight, d.offsetHeight);
    }
    // UI-геометрия: нижняя граница содержимого в пикселях.
    return Math.ceil(bottom);
  }

  function apply() {
    if (!global.BX24 || !BX24.resizeWindow) return;
    var open = document.querySelector('.modal-back');
    // Пока открыт диалог, высоту не трогаем: модалка позиционируется по окну, и
    // подгонка под неё дёргает экран прямо под курсором человека.
    if (open) return;

    var h = Math.min(MAX_HEIGHT, Math.max(frameFloor, contentHeight() + 16));
    // Просим портал только при заметном изменении: иначе каждый перерисованный
    // список шлёт по десятку одинаковых запросов подряд.
    if (Math.abs(h - lastSent) < 24) return;
    lastSent = h;
    // Страницу открыли не в портале (прямой адрес, отладка) — заказывать высоту
    // окна некому и незачем: вёрстка работает и без этого вызова.
    try { BX24.resizeWindow(global.innerWidth || 900, h); } catch (e) { /* вне портала окна нет — заказывать высоту нечему */ }
  }

  /** Подогнать высоту (с небольшой задержкой, чтобы браузер успел разложить контент). */
  function sync() {
    clearTimeout(timer);
    timer = setTimeout(apply, 60);
  }

  if (global.BX24) {
    BX24.init(function () { sync(); });
  }
  global.addEventListener('load', sync);
  global.addEventListener('resize', sync);

  // Контент меняется — высота меняется. Наблюдатель избавляет прикладной код от
  // обязанности помнить про вызов после каждой перерисовки списка.
  // Следим и за видимостью: показать/скрыть блок — такое же изменение высоты,
  // как и правка содержимого, а по childList оно не видно вовсе.
  if (global.MutationObserver) {
    new MutationObserver(sync).observe(document.documentElement, {
      childList: true, subtree: true, characterData: true,
      // class обязателен: разделы прячутся классом .hidden, и без него смена
      // экрана проходит мимо наблюдателя — окно остаётся высотой прошлого,
      // более длинного раздела, а под коротким висит белая полоса.
      attributes: true, attributeFilter: ['hidden', 'style', 'class']
    });
  }

  global.appFrame = { sync: sync };
})(window);
